"""Embed project assets in main.tex for the single-file document editor.

The canonical style, bibliography and figures stay in their normal project paths.
This only synchronizes copies; it does not compile or run any experiment.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN = '% BEGIN EDITOR ASSETS (generated by code/sync_paper_assets.py)'
END = '% END EDITOR ASSETS'


def main():
    paper = ROOT / 'paper'
    path = paper / 'main.tex'
    source = path.read_text()
    if BEGIN in source:
        a = source.index(BEGIN)
        b = source.index(END, a) + len(END)
        source = (source[:a] + source[b:]).lstrip('\n')
    assets = [BEGIN]
    for name in ['neurips_2025.sty', 'references.bib']:
        assets += [rf'\begin{{filecontents*}}{{{name}}}', (paper / name).read_text().rstrip(), r'\end{filecontents*}']
    assets += [END, '']
    source = '\n'.join(assets) + '\n' + source
    for key in ['title_abstract', 'body_clean']:
        start = f'% BEGIN INLINE FIGURE {key}'
        end = f'% END INLINE FIGURE {key}'
        a = source.index(start) + len(start)
        b = source.index(end, a)
        drawing = (paper / 'figures' / f'lexical-gap-{key}.tex').read_text().rstrip()
        source = source[:a] + '\n' + drawing + '\n' + source[b:]
    path.write_text(source)
    print('Synchronized editor assets:', path)


if __name__ == '__main__':
    main()
